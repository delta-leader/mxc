!************************************************************************
!*         This module file is to make weights and evaluation points    *
!*              of Gauss integration for triangle elements.             *
!*                                                                      *
!*              "integ" is the parameter of number of division,         *
!*               and can be chosen 3, 4, 7, 13, 27, 48, 79.             *
!*                                                    coded by maruyama *
!************************************************************************
subroutine Gauss_tri(n,gzi1,gzi2,gzi3,wi)
  implicit none
  integer,parameter::n_ava=7
  integer,dimension(n_ava),parameter::ni_ava=(/3,4,7,13,27,48,79/)
  integer::i
  integer,intent(in)::n
  real(kind(0d0)),dimension(:),allocatable,intent(inout)::gzi1,gzi2,gzi3,wi
  !---------------------------------------------------------
  do i=1,n_ava
     if(n == ni_ava(i))exit
     if(i == n_ava)then
        write(*,*)"check integration number for Gauss_tri!!"
        stop
     end if
  end do
  if(allocated(gzi1)) deallocate(gzi1)
  if(allocated(gzi2)) deallocate(gzi2)
  if(allocated(gzi3)) deallocate(gzi3)
  if(allocated(wi)) deallocate(wi)
  allocate(gzi1(n),gzi2(n),gzi3(n),wi(n))
  call calc_Gauss_pw_tri(n,gzi1,gzi2,gzi3,wi)
end subroutine Gauss_tri
